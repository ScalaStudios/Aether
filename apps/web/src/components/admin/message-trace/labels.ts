import type { Tone } from "@/components/status-badge"
import type { MessageTraceStatus } from "@/lib/types"

export const traceStatuses: Record<MessageTraceStatus, { label: string; tone: Tone }> = {
  delivered: { label: "Delivered", tone: "success" },
  junk: { label: "Delivered to Junk", tone: "warning" },
  queued: { label: "In queue", tone: "info" },
  deferred: { label: "Deferred", tone: "warning" },
  held: { label: "Held", tone: "warning" },
  bounced: { label: "Bounced", tone: "danger" },
  rejected: { label: "Rejected", tone: "danger" },
  discarded: { label: "Discarded", tone: "neutral" },
  deleted: { label: "Deleted", tone: "neutral" },
  unknown: { label: "No delivery record", tone: "neutral" },
}

export function arrival(service: string) {
  switch (service) {
    case "smtpd":
      return "From another mail server"
    case "submission":
    case "submissions":
      return "Sent by a signed-in user"
    case "sieve-relay":
      return "Forwarded by a mail rule"
    case "pickup":
      return "Submitted on the mail server"
  }
  return "Generated by the mail server"
}

export function formatTLS(tls: string) {
  const [protocol, cipher] = tls.split(" ")
  return `${protocol.replace(/^TLSv/, "TLS ")}${cipher ? ` · ${cipher}` : ""}`
}
